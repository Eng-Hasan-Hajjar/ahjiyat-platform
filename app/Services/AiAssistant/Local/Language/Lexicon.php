    /** يطوي صيغة سطحية: TextFold ثم تجريد «ال» من كل كلمة (إن بقي ≥3 أحرف). */
    public static function key(string $surface): string
    {
        $folded = preg_replace('/[^\p{L}\p{N}\s]+/u', ' ', TextFold::fold($surface)) ?? '';
        $words = array_filter(explode(' ', $folded), fn ($w) => $w !== '');

        return implode(' ', array_map(fn (string $w) => self::stripAl($w), $words));
    }

    public static function stripAl(string $word): string
    {
        if (mb_strlen($word) >= 5 && str_starts_with($word, 'ال')) {
            return mb_substr($word, 2);
        }

        return $word;
    }

    /** @return array<string, string> */
    public static function singles(): array
    {
        self::boot();

        return self::$single;
    }

    /** كل كلمات العبارات المعجمية (بلا «ال») كي لا تُعامَل كأخطاء إملائية. @return array<string, true> */
    public static function phraseTokens(): array
    {
        self::boot();

        if (self::$phraseTokens === null) {
            self::$phraseTokens = [];

            foreach (array_merge(array_keys(self::$phrases), array_keys(self::$facetPhrases)) as $phrase) {
                foreach (explode(' ', $phrase) as $word) {
                    self::$phraseTokens[$word] = true;
                }
            }
        }

        return self::$phraseTokens;
    }

