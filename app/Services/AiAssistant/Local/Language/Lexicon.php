    public static function concepts(): array
    {
        return array_keys(self::CONCEPTS);
    }

    private static function boot(): void
    {
        if (self::$single !== null) {
            return;
        }

        self::$single = self::$phrases = self::$facetSingle = self::$facetPhrases = [];

        foreach (self::CONCEPTS as $concept => $surfaces) {
            foreach (explode('|', $surfaces) as $surface) {
                $key = self::key($surface);

                if ($key === '') {
                    continue;
                }

                $words = substr_count($key, ' ') + 1;

                if ($words === 1) {
                    self::$single[$key] ??= $concept;
                } else {
                    self::$phrases[$key] ??= $concept;
                    self::$maxPhrase = max(self::$maxPhrase, $words);
                }
            }
        }

        foreach (self::FACETS as $facet => $surfaces) {
            foreach (explode('|', $surfaces) as $surface) {
                $key = self::key($surface);

                if ($key === '') {
                    continue;
                }

                $words = substr_count($key, ' ') + 1;

                if ($words === 1) {
                    self::$facetSingle[$key] ??= $facet;
                } else {
                    self::$facetPhrases[$key] ??= $facet;
                    self::$maxFacetPhrase = max(self::$maxFacetPhrase, $words);
                }
            }
        }
    }
