    /** @return string|null مفتاح الموضوع غير الموثَّق الأقرب (يُمرَّر إلى undocumented). */
    public static function topicOf(string $folded): ?string
    {
        foreach (self::UNDOCUMENTED as $topic => $words) {
            foreach ($words as $w) {
                if (preg_match('/(^|\s)'.preg_quote($w, '/').'(\s|$)/u', $folded) === 1) {
                    return $topic;
                }
            }
        }

        return null;
    }

    /** موضوع معروف الغياب عن الدليل المنشور: لا نؤكد وجوده ولا عدمه. */
    public static function undocumented(?string $topic): string
    {
        $name = match ($topic) {
            'mobile_app' => 'تطبيق للجوال',
            'company' => 'بيانات عن الجهة المالكة أو فريق العمل',
            'language_other' => 'لغة أخرى للواجهة',
