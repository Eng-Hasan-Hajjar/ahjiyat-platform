            'user_count' => 'أعداد المستخدمين أو إحصاءات المنصة',
            'subscription' => 'اشتراك مدفوع أو أسعار',
            'crypto', 'payment_method' => 'طرق دفع أو تحويل محددة',
            'exact_amounts' => 'مبالغ أو أرقام محددة',
            default => 'هذا الموضوع',
        };

        return 'لا يذكر دليل المنصة المنشور حاليًا شيئًا عن '.$name.'، لذلك لا أستطيع تأكيد توفره ولا إعطاء تفاصيل عنه. يمكنك مراجعة مركز المساعدة للتأكد.';
    }

    /** @param list<string> $options أسماء ميزات (مقالات) مرشَّحة، من اثنين إلى أربعة */
    public static function clarify(array $options): string
    {
        $options = array_values(array_unique(array_filter($options)));

        if (count($options) < 2) {
            return 'سؤالك يحتمل أكثر من معنى. أخبرني أي ميزة تقصد (مثل الجواهر أو الفرق أو المنافسات أو المتجر) لأشرحها لك.';
        }

        return 'سؤالك يحتمل أكثر من معنى. هل تقصد: '.implode('، أو ', array_map(fn (string $o) => '«'.$o.'»', array_slice($options, 0, 4))).'؟ أخبرني أيّها تريد لأشرحه لك.';
    }
