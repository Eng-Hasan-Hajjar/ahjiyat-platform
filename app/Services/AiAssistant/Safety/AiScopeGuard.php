/**
 * E45 - حارس النطاق والخصوصية (حتمي، قبل النموذج): تحية/تعريف، حقن تعليمات، خصوصية، طلبات تنفيذ، خارج النطاق.
 *
 * الترتيب: فارغ ← حقن ← خصوصية ← تنفيذ ← تحية/تعريف ← خارج النطاق. كل شيء غير ذلك يمر للاسترجاع والنموذج، والامتناع عند غياب الدليل يتكفّل بالباقي.
 * «خارج النطاق» لا يُرفض إلا إن لم تحتوِ الرسالة أي مفردة من معجم المنصة (حتى لا نرفض سؤالًا مشروعًا بصياغة غريبة).
 */
final class AiScopeGuard
{
    private const INJECTION = '/تجاهل\s+(?:كل\s+)?(?:ال)?(?:تعليمات|اوامر|قواعد|ما\s+سبق)|انس(?:ى)?\s+(?:كل\s+)?(?:ما|التعليمات)|(?:اكشف|اظهر|اعرض|اطبع|كرر|اعد)\s+(?:لي\s+)?(?:ال)?(?:تعليماتك|برومبت|prompt|رسالة\s+النظام|التعليمات\s+(?:الاصليه|الداخليه|السابقه))|ما\s+(?:هي|هو)\s+(?:ال)?(?:تعليماتك|برومبتك|prompt)|system\s*prompt|developer\s*mode|jailbreak|\bdan\b|ignore\s+(?:all\s+|the\s+|your\s+)?(?:previous|prior|above)|reveal\s+(?:your|the)\s+(?:prompt|instructions)|you\s+are\s+now|act\s+as\b|pretend\s+(?:to\s+be|you)|تصرف\s+(?:ك|كانك|كما\s+لو)|من\s+الان\s+(?:انت|فانت)|اعتبر\s+نفسك|انت\s+الان\s+(?:لست|حر)|بدون\s+قيود|وضع\s+المطور|repeat\s+(?:the\s+)?(?:above|everything)|<\|[a-z_]+\|>|\[\s*(?:system|inst)\s*\]|^\s*#{2,}\s*(?:system|instructions?)/iu';

    private const PRIVACY = '/(?:محادث[هة]|رسال[هة]|دردش[هة]|رسائل|محادثات)\s+(?:\S+\s+){0,2}(?:ال)?(?:خاصه|خصوصيه|سريه)|(?:محادث(?:ه|ات|تي|اتي)|دردش(?:ه|ات|تي|اتي)|رسائل(?:ي)?|رسايل)\s*(?:ال)?(?:خاصه|خصوصيه|سريه)|(?:محادثات|رسائل|دردشات|دردشه)\s*(?:ال)?(?:اخرين|اخر|لاعب|مستخدم|صديق|فلان)|private\s+(?:chat|messages?|dm)|\bdm\b|(?:قضيه|قضايا|ملف|ملفات|حاله|حالات|سجل|سجلات|ملاحظات)\s*(?:ال)?(?:اشراف|مراقبه|ادارة|اداره)|moderation\s+(?:case|log|notes?)|من\s+(?:ابلغ|بلغ|قدم\s+بلاغ)\s+(?:عني|ضدي|علي)|(?:اثبات|ايصال|صوره|وصل|اشعار)\s*(?:ال)?(?:دفع|حواله|تحويل)|payment\s+proof|receipt|(?:كلمه|كلمات|باسورد|رمز)\s*(?:ال)?(?:مرور|سر|سري)\s*(?:ل|الخاص|الخاصه|قاعده|الخادم|الاداره|المدير|الادمن|لوحه)|(?:مفتاح|مفاتيح)\s*(?:ال)?(?:api|واجهه|تشفير|خادم|مزود|openai)|\.env|متغيرات\s+(?:ال)?(?:بيئه|خادم)|اعدادات\s+(?:ال)?(?:خادم|سيرفر|قاعده\s+البيانات)|بيانات\s+(?:الاتصال|الدخول)\s+(?:ب|ل|الي)?\s*(?:قاعده|الخادم|لوحه|الاداره)|database\s+(?:password|credentials)|api\s*key|secret\s*key|\btoken\b|\bssh\b|(?:ايميل|بريد|هاتف|جوال|رقم\s+هاتف|عنوان\s+ip|\bip\b|موقع|عنوان)\s*(?:ال)?(?:مستخدم|لاعب|صديق|فلان|كاتب|مبدع|عضو)|(?:رصيد|جواهر|نقاط|محفظه|مشتريات|اجهزه|جلسات|سجل\s+دخول)\s*(?:ال)?(?:مستخدم|لاعب|صديقي|فلان|عضو)\s*\S*|كم\s+(?:جوهره|جواهر|نقطه|نقاط|رصيد)\s+(?:يملك|عند|لدي)\s+(?!ي\b)(?:ال)?(?:مستخدم|لاعب|فلان|صديقي)/iu';

    private const ACTION_VERBS = 'احذف|امسح|الغ|الغي|اشتر|اشتري|ادفع|حول|ارسل|ابعث|صوت|امنحني|امنح|اجعلني|زور|اخترق|عدل\s+لي|غير\s+لي';

    private const ACTION = '/^\s*(?:(?:من\s+فضلك|لو\s+سمحت|رجاء|يا\s+تطور|تطور)\s*[,،:]?\s*)?(?:(?:'.self::ACTION_VERBS.')\b|(?:اعطني|اعطيني|هات|زد|زيد|ارفع|اضف|اضيف|فعل|عطل|اشترك|سجلني|احجز|اطلب)\s+(?:لي\s+|لنا\s+)?(?:\d+\s+)?(?:ال)?(?:جواهر|جوهره|نقاط|نقطه|رصيد|حساب|اشتراك|باس|بطاقه|عنصر|متجر|ترتيبي|مستواي|خبره|صلاحيه|مكافاه|هديه|اسم|اي?ميل|كلمه)|(?:buy|delete|remove|send|pay|transfer|grant|give\s+me|vote\s+for)\b)/iu';

    private const GREETING = '/^\s*(?:ي?ا?\s*)?(?:مرحبا|مرحبتين|اهلا|اهلين|هلا|هلا\s+و?غلا|سلام|السلام\s+عليكم(?:\s+و?رحمه\s+الله(?:\s+و?بركاته)?)?|صباح\s+(?:الخير|النور)|مساء\s+(?:الخير|النور)|هاي|هالو|هلو|hi|hello|hey|شكرا|شكرا\s+لك|شكرا\s+جزيلا|مشكور|يعطيك\s+العافيه|thanks?|thank\s+you|تمام|حسنا|اوكي|ok|okay)(?:\s+(?:تطور|يا\s+تطور|بك|فيك|عليكم))?\s*[!.،,؟?\x{061F}]*\s*$/iu';

    private const IDENTITY = '/^\s*(?:(?:ي?ا?\s*تطور\s*[,،]?\s*)?)(?:من\s+انت|مين\s+انت|ما\s+اسمك|شو\s+اسمك|عرفني\s+(?:ب|على)\s*نفسك|عرف\s+نفسك|من\s+(?:صنعك|برمجك|طورك)|ماذا\s+(?:تستطيع|يمكنك)(?:\s+ان)?(?:\s+تفعل)?|ماذا\s+تفعل|ماذا\s+تقدم(?:\s+لي)?|ما\s+(?:هي\s+)?(?:قدراتك|وظيفتك|مهمتك)|هل\s+انت\s+(?:انسان|بشر|روبوت|chat\s*gpt|chatgpt|gpt|ذكاء\s+اصطناعي)|what\s+can\s+you\s+do|who\s+are\s+you|what\s+are\s+you|are\s+you\s+(?:a\s+)?(?:human|bot|chatgpt|gpt))\s*[!.،,؟?\x{061F}]*\s*$/iu';

    private const OUT_OF_SCOPE = '/(?:اكتب|ولد|انشئ|صمم)\s+(?:لي\s+)?(?:ال)?(?:كود|برنامج|سكربت|دال[هة]|قصيد[هة]|مقال[هة]?|قصه|رواي[هة]|بحث|موضوع\s+تعبير|سيره\s+ذاتيه|اغنيه)|ترجم\s|ترجمه|حل\s+(?:لي\s+)?(?:ال)?(?:معادله|واجب|مساله|تمرين)|(?:ال)?(?:طقس|درجه\s+الحراره|نشره\s+الاخبار|اخبار\s+اليوم)|(?:سعر|اسعار)\s+(?:ال)?(?:ذهب|فضه|عملات|اسهم|دولار|يورو|بيتكوين|نفط)|(?:ال)?(?:انتخابات|حكومه|رئيس\s+(?:ال)?(?:دوله|وزراء|جمهوريه)|وزير|سياسي|حزب|حرب)|وصفه\s+(?:طبخ|اكل|حلويات)|(?:تشخيص|علاج|دواء|ادويه|اعراض|مرض)|(?:استثمار|تداول|اسهم|بورصه|عملات\s+رقميه|قرض|ضريبه)|(?:محام[يى]|قضيه\s+قانونيه|استشاره\s+قانونيه|عقد\s+زواج)|(?:نكته|نكت)\b|(?:ما\s+هي\s+)?عاصم[هة]|من\s+هو\s+(?:ال)?(?:رئيس|ملك|مخترع|اشهر)|برمج[هة]|كاس\s+(?:ال)?عالم|كره\s+(?:ال)?قدم|مباراه|مباريات|(?:افضل|احسن)\s+(?:لغه|هاتف|جوال|لابتوب|سياره|فيلم|مسلسل)|\bpython\b|\bjavascript\b|\bphp\b|\bsql\b|\bwrite\s+(?:a|an|me)\b|\bcode\s+(?:for|to)\b|\bweather\b|\bstock\b|\bbitcoin\b|\brecipe\b/iu';

    /** معجم المنصة (مطوي): وجود أيٍّ منها يعني أن السؤال داخل النطاق المحتمل. */
    private const LEXICON = '/احجي|لغز|الغاز|جواهر|جوهر|نقاط|نقطه|منصه|ahjiyat|تطور|فريق|فرق|صديق|اصدقاء|موسم|مواسم|باس|متجر|عنصر|مبدع|سلسل|انجاز|وسام|اوسمه|ترتيب|صدار|بطول|مسابق|تحدي|دوري|كاتب|كتاب|داعم|دعم|حسابي|حساب|ملفي|اشعار|محادث|دردش|لاعب|مستوي|تقدم|خبره|\bxp\b|هديه|مكافا|حمله|مرحل|جائز|حظر|بلاغ|مساعد|دليل|اشتراك|خصوصي|شروط|سياس|رعاي|راعي|تذكره|بطاق|عرض|حدث|فعاليه/u';

    /** سؤال عن بيانات حساب السائل نفسه (رصيدي/نجومي/لدي…): الجواب الرقمي له لا يصح إلا من أداة «حسابي». */
    private const PERSONAL = '/(?<![\p{L}\p{N}])(?:لدي|عندي|املك|رصيدي|نجومي|نقاطي|جواهري|مستواي|ترتيبي|حسابي|ملفي|فريقي|مشترياتي|طلباتي|تقدمي|انجازاتي|خبرتي|محفظتي|اشتراكي|بطاقتي|مهامي|سلسلتي)(?![\p{L}\p{N}])/u';

    public function isPersonalQuestion(string $text): bool
    {
        return preg_match(self::PERSONAL, TextFold::fold($text)) === 1;
    }

    /** هل تذكر الرسالة مفردة من معجم المنصة؟ (لتحديد جدوى استدعاء النموذج/الأدوات عند غياب المعرفة). */
    public function mentionsPlatform(string $text): bool
    {
        return preg_match(self::LEXICON, TextFold::fold($text)) === 1;
    }

    public function inspect(string $text): GuardVerdict
    {
        $folded = TextFold::fold($text);

        if ($folded === '' || preg_match('/[\p{L}\p{N}]/u', $folded) !== 1) {
            return new GuardVerdict(GuardVerdict::CANNED, 'empty');
        }

        if (preg_match(self::INJECTION, $folded) === 1 || preg_match(self::INJECTION, $text) === 1) {
            return new GuardVerdict(GuardVerdict::REFUSE, 'injection', 'out_of_scope');
        }

        if (preg_match(self::PRIVACY, $folded) === 1) {
            return new GuardVerdict(GuardVerdict::REFUSE, 'privacy', 'privacy_refusal');
        }

        if (preg_match(self::ACTION, $folded) === 1) {
            return new GuardVerdict(GuardVerdict::REFUSE, 'action', 'action_refusal');
        }

        if (preg_match(self::GREETING, $folded) === 1) {
            return new GuardVerdict(GuardVerdict::CANNED, 'greeting');
        }

        if (preg_match(self::IDENTITY, $folded) === 1) {
            return new GuardVerdict(GuardVerdict::CANNED, 'identity');
        }

        if (preg_match(self::OUT_OF_SCOPE, $folded) === 1 && preg_match(self::LEXICON, $folded) !== 1) {
            return new GuardVerdict(GuardVerdict::REFUSE, 'out_of_scope', 'out_of_scope');
        }

        return GuardVerdict::allow();
    }
}
